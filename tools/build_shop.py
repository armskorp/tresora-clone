"""Shop layer for the static copy:
 - assets/js/catalog.js            client-side catalog (display only; prices are informational)
 - checkout-server/src/catalog.js  server-side price list (authoritative for Stripe)
 - products/<handle>.html          product pages with variant + quantity + add to cart
 - success.html / cancel.html      Stripe Checkout return pages
 - injects config.js / catalog.js / cart.js / shop.css into index.html
Run after tools/build.py.  Source data: orig/products.json (Shopify /products.json)."""
import json, os, re, html, subprocess, hashlib, time, urllib.parse as up
ROOT = "/workspace/tresora-clone"; os.chdir(ROOT)
UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/129.0 Safari/537.36"
SITE = "https://armskorp.github.io/tresora-clone"
products = json.load(open("orig/products.json"))["products"]
os.makedirs("assets/images/products", exist_ok=True); os.makedirs("checkout-server", exist_ok=True)

def img(url, w):
    p = up.urlparse(url); q = dict(up.parse_qsl(p.query)); q["width"] = str(w)
    u = up.urlunparse(p._replace(query=up.urlencode(q)))
    stem, ext = os.path.splitext(os.path.basename(p.path))
    out = f"assets/images/products/{re.sub(r'[^A-Za-z0-9_-]', '_', stem)[:50]}-{hashlib.md5(p.path.encode()).hexdigest()[:6]}-w{w}{ext}"
    if not os.path.exists(out) or os.path.getsize(out) == 0:
        for a in range(4):
            if subprocess.run(["curl", "-sfL", "-A", UA, "-o", out, u]).returncode == 0 and os.path.getsize(out): break
            time.sleep(2 + 3 * a)
    return out

def cents(s): return int(round(float(s) * 100))

client, server = {"products": {}, "variants": {}}, {"currency": "usd", "variants": {}}
for p in products:
    main = p["images"][0]["src"] if p["images"] else None
    pimg = img(main, 800) if main else ""
    pthumb = img(main, 200) if main else ""
    client["products"][str(p["id"])] = {"id": p["id"], "handle": p["handle"], "title": p["title"], "image": pimg,
                                        "variants": [v["id"] for v in p["variants"]]}
    for v in p["variants"]:
        fi = (v.get("featured_image") or {}).get("src") or main
        vt = img(fi, 200) if fi else pthumb
        vimg = img(fi, 800) if fi else pimg
        vtitle = "" if v["title"] == "Default Title" else v["title"]
        client["variants"][str(v["id"])] = {"id": v["id"], "product_id": p["id"], "handle": p["handle"], "title": p["title"],
            "variant_title": vtitle, "price": cents(v["price"]), "available": bool(v["available"]), "thumb": vt, "image": vimg}
        server["variants"][str(v["id"])] = {"product_id": p["id"], "name": p["title"] + (f" – {vtitle}" if vtitle else ""),
            "unit_amount": cents(v["price"]), "available": bool(v["available"]), "image": f"{SITE}/{vimg}"}

open("assets/js/catalog.js", "w").write("/* Generated by tools/build_shop.py from products.json – display data only. */\nwindow.TRESORA_CATALOG = " + json.dumps(client, ensure_ascii=False, indent=1) + ";\n")
os.makedirs("checkout-server/src", exist_ok=True)
open("checkout-server/src/catalog.js", "w").write("/* Generated by tools/build_shop.py from the store's products.json.\n   SERVER-SIDE PRICE LIST: the only source of prices for Stripe. unit_amount is in cents (USD). */\nexport default " + json.dumps(server, ensure_ascii=False, indent=1) + ";\n")

# ---------- shared page chrome for product / return pages ----------
LOGO = "assets/images/25d07e5ce9255cb0bd9e82c85fc13b9d-h100-61ae14.png"
CART_SVG = '<svg viewBox="0 0 20 20" width="20" height="20" fill="none" aria-hidden="true"><path d="M4.5 6.5h11l-.9 9.1a1.5 1.5 0 0 1-1.5 1.4H6.9a1.5 1.5 0 0 1-1.5-1.4L4.5 6.5Z" stroke="currentColor" stroke-width="1.4"/><path d="M7.5 8V5.5a2.5 2.5 0 0 1 5 0V8" stroke="currentColor" stroke-width="1.4"/></svg>'
def page(title, body, base="../", desc=""):
    return f"""<!doctype html>
<html lang="en" data-base="{base}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{html.escape(title)}</title>{f'<meta name="description" content="{html.escape(desc)}">' if desc else ''}
<link rel="icon" href="{base}assets/images/favicon.png"><link rel="stylesheet" href="{base}assets/css/shop.css"></head>
<body class="tp">
<div class="tp-announce">FREE US SHIPPING ON ALL ORDERS</div>
<header class="tp-header"><a class="tp-logo" href="{base}index.html"><img src="{base}{LOGO}" alt="TRESORA" width="96" height="62"></a>
<button class="tp-cart-btn" type="button" data-cart-open aria-label="Cart">{CART_SVG}<span class="tp-bubble" data-cart-count hidden>0</span></button></header>
<main class="tp-main">{body}</main>
<footer class="tp-footer">© 2026 TRESORA</footer>
<script src="{base}assets/js/config.js"></script><script src="{base}assets/js/catalog.js"></script><script src="{base}assets/js/cart.js"></script>
</body></html>"""

def strip_meta(h): return re.sub(r"<meta[^>]*>", "", h or "")
for p in products:
    vs = p["variants"]; v0 = next((v for v in vs if v["available"]), vs[0])
    cv = client["variants"][str(v0["id"])]
    opts = ""
    if len(vs) > 1:
        name = html.escape(p["options"][0]["name"])
        radios = "".join(
            f'<label class="tp-pill"><input type="radio" name="variant" value="{v["id"]}" {"checked" if v is v0 else ""} {"" if v["available"] else "disabled"}><span>{html.escape(v["title"])}</span></label>'
            for v in vs)
        opts = f'<fieldset class="tp-options"><legend>{name}</legend>{radios}</fieldset>'
    else:
        opts = f'<input type="hidden" name="variant" value="{v0["id"]}">'
    avail = any(v["available"] for v in vs)
    body = f"""
<nav class="tp-crumb"><a href="../index.html">Home</a> / <span>{html.escape(p['title'])}</span></nav>
<div class="tp-product" data-product-id="{p['id']}">
  <div class="tp-media"><img data-variant-image src="../{cv['image']}" alt="{html.escape(p['title'])}" width="800" height="800"></div>
  <div class="tp-info">
    <h1>{html.escape(p['title'])}</h1>
    <p class="tp-price" data-variant-price>${v0['price']} USD</p>
    <form class="tp-form" data-add-form>
      {opts}
      <div class="tp-qty-row"><span class="tp-label">Quantity</span>
        <div class="tc-qty"><button type="button" data-step="-1" aria-label="Decrease quantity">−</button><input name="quantity" type="number" min="1" max="20" value="1" inputmode="numeric" aria-label="Quantity"><button type="button" data-step="1" aria-label="Increase quantity">+</button></div></div>
      <button class="tc-button tp-add" type="submit" {"" if avail else "disabled"}>{"Add to cart" if avail else "Sold out"}</button>
    </form>
    <div class="tp-desc">{strip_meta(p.get('body_html'))}</div>
  </div>
</div>"""
    open(f"products/{p['handle']}.html", "w").write(page(f"{p['title']} – TRESORA", body))

open("success.html", "w").write(page("Thank you – TRESORA", """
<section class="tp-return" data-checkout-success><h1>Thank you!</h1><p>Your order has been placed. A confirmation email is on its way.</p>
<a class="tc-button" href="index.html">Continue shopping</a></section>""", base=""))
open("cancel.html", "w").write(page("Checkout canceled – TRESORA", """
<section class="tp-return"><h1>Checkout canceled</h1><p>No payment was taken. Your cart is still saved.</p>
<button class="tc-button" type="button" data-cart-open>View cart</button> <a class="tc-link" href="index.html">Continue shopping</a></section>""", base=""))

# ---------- inject into homepage (idempotent) ----------
idx = open("index.html", encoding="utf-8").read()
if "assets/js/cart.js" not in idx:
    idx = idx.replace("</head>", '<link href="assets/css/shop.css" rel="stylesheet"/>\n</head>', 1)
    idx = idx.replace("</body>", '<script src="assets/js/config.js"></script>\n<script src="assets/js/catalog.js"></script>\n<script src="assets/js/cart.js"></script>\n</body>', 1)
    open("index.html", "w", encoding="utf-8").write(idx)
print("catalog:", len(client["variants"]), "variants;", len(products), "product pages")
